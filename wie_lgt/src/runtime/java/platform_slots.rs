//! Where each platform class keeps its virtual methods in a dispatch table.
//!
//! A class's own methods start at slot 10, after `<init>` and
//! `java/lang/Object`'s nine. Which of *its* methods lands where is decided by
//! the platform, over the class's whole method table - and the table an
//! application registers lists only the methods it imports, so numbering the
//! imported ones in order gets the right answer only for a class an
//! application uses completely.
//!
//! Legend of Master reaches `java/lang/String` slot 16 and imports none of
//! `String`'s virtual methods, so nothing in the application says what slot 16
//! is. It is `compareTo`.
//!
//! Read out of `liblgt_system.so`, whose `dt_<class>` symbols are the tables
//! themselves and whose method tables give the descriptors. A class that is
//! not here falls back to numbering the imported methods in order.

