/// The method a class puts in `slot`, if the layout is known.
///
/// This is what answers a call the application makes on an object of a class
/// it never imported - `getClass().getResourceAsStream(...)` reaches
/// `java/lang/Class` slot 16, and nothing the application registers says what
/// that is.
pub fn platform_method(class: &str, slot: u32) -> Option<(&'static str, &'static str)> {
    let slots = PLATFORM_DISPATCH_SLOTS.iter().find(|(known, _)| *known == class)?.1;

    slots
        .iter()
        .find(|(known, _, _)| *known == slot)
        .map(|(_, name, descriptor)| (*name, *descriptor))
}

/// The slot `class.name descriptor` occupies, if the layout is known.
pub fn platform_slot(class: &str, name: &str, descriptor: &str) -> Option<u32> {
    let slots = PLATFORM_DISPATCH_SLOTS.iter().find(|(known, _)| *known == class)?.1;

    slots
        .iter()
        .find(|(_, known_name, known_descriptor)| *known_name == name && *known_descriptor == descriptor)
        .map(|(slot, _, _)| *slot)
}

#[cfg(test)]
mod tests {
    use super::{PLATFORM_DISPATCH_SLOTS, platform_slot};

    /// The ten slots before a class's own are fixed, so every table has to
    /// agree about them.
    #[test]
    fn object_slots_are_the_same_everywhere() {
        for (class, slots) in PLATFORM_DISPATCH_SLOTS {
            for (slot, name, descriptor) in slots.iter().filter(|(slot, _, _)| (1..10).contains(slot)) {
                let object = platform_slot("java/lang/Object", name, descriptor);

                assert_eq!(object, Some(*slot), "{class} puts {name}{descriptor} at slot {slot}");
            }
        }
    }

    #[test]
    fn a_class_uses_each_slot_once() {
        for (class, slots) in PLATFORM_DISPATCH_SLOTS {
            for (index, (slot, _, _)) in slots.iter().enumerate() {
                assert!(
                    slots[..index].iter().all(|(earlier, _, _)| earlier != slot),
                    "{class} uses slot {slot} twice"
                );
            }
        }
    }

    #[test]
    fn a_slot_names_the_method_the_class_put_there() {
        use super::platform_method;

        assert_eq!(
            platform_method("java/lang/Class", 16),
            Some(("getResourceAsStream", "(Ljava/lang/String;)Ljava/io/InputStream;"))
        );
        assert_eq!(platform_method("java/lang/Object", 2), Some(("hashCode", "()I")));
        assert_eq!(platform_method("java/lang/Class", 999), None);
        assert_eq!(platform_method("no/such/Class", 1), None);
    }

    #[test]
    fn known_layouts_start_at_ten() {
        assert_eq!(platform_slot("java/lang/String", "compareTo", "(Ljava/lang/String;)I"), Some(16));
        assert_eq!(platform_slot("org/kwis/msp/lcdui/Card", "showNotify", "(Z)V"), Some(16));
        assert_eq!(platform_slot("java/lang/Thread", "start", "()V"), Some(10));
        assert_eq!(platform_slot("java/lang/String", "nonesuch", "()V"), None);
        assert_eq!(platform_slot("no/such/Class", "toString", "()Ljava/lang/String;"), None);
    }
}
