/// Waveform samples per operator wave, and waves in the set.
pub const WAVE_SIZE: usize = 1024;
pub const WAVE_COUNT: usize = 32;

/// Points the low frequency oscillator is sampled at, and depths of each.
const LFO_TABLE_SIZE: usize = 4096;
const LFO_DEPTHS: usize = 4;

static WAVES: &[u8; WAVE_COUNT * WAVE_SIZE * 2] = include_bytes!("data/waves.bin");
static LFO_LEVEL: &[u8; LFO_DEPTHS * LFO_TABLE_SIZE * 4] = include_bytes!("data/lfo_level.bin");
static LFO_PITCH: &[u8; LFO_DEPTHS * LFO_TABLE_SIZE * 4] = include_bytes!("data/lfo_pitch.bin");

/// One sample of `waveform`, at `index` within its period.
pub fn wave_sample(waveform: usize, index: usize) -> i32 {
    let offset = ((waveform & (WAVE_COUNT - 1)) * WAVE_SIZE + (index & (WAVE_SIZE - 1))) * 2;

    i16::from_le_bytes([WAVES[offset], WAVES[offset + 1]]) as i32
}

fn lfo_value(table: &[u8], depth: usize, phase: usize) -> i32 {
    let offset = ((depth & (LFO_DEPTHS - 1)) * LFO_TABLE_SIZE + (phase & (LFO_TABLE_SIZE - 1))) * 4;

    i32::from_le_bytes([table[offset], table[offset + 1], table[offset + 2], table[offset + 3]])
}

/// Tremolo, as a Q15 multiplier on the operator's output level.
pub fn lfo_level_q15(depth: usize, phase: usize) -> i32 {
    lfo_value(LFO_LEVEL, depth, phase)
}

/// Vibrato, as a Q20 multiplier on the operator's phase step.
pub fn lfo_pitch_q20(depth: usize, phase: usize) -> i64 {
    lfo_value(LFO_PITCH, depth, phase) as i64
}

